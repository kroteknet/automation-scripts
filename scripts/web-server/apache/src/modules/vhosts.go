// ensureValidMainConfig verifies that the main configuration exists and has valid contents.
// If missing or truncated (< 80 bytes), it populates it with a clean production template.
func EnsureValidMainConfig() {
	mainConf := "/etc/apache2/apache2.conf"
	if core.SysInfo.Family == "rhel" {
		mainConf = "/etc/httpd/conf/httpd.conf"
		_ = os.MkdirAll("/etc/httpd/conf", 0755)
		_ = os.MkdirAll("/etc/httpd/conf.d", 0755)
		_ = os.MkdirAll("/var/log/httpd", 0755)
	} else if core.SysInfo.Family == "alpine" {
		mainConf = "/etc/apache2/httpd.conf"
		_ = os.MkdirAll("/etc/apache2/conf.d", 0755)
	}

	stat, err := os.Lstat(mainConf)
	if os.IsNotExist(err) || (err == nil && stat.Mode().IsRegular() && stat.Size() < 80) {
		_ = system.WriteFileNoFollow(mainConf, []byte(GetDefaultMainConfig()), 0644, "")
	}
}

// runEditor opens the specified file in the user's preferred editor ($EDITOR),
// falling back to nano, vim, or vi. The editor is attached directly to /dev/tty.

func DoAddDomain() {
	tui.ClearScreen()
	cardLines := []string{
		core.BOLD + core.CYAN + "Add New Virtual Host / Domain Configuration" + core.NC,
		"",
		"  Specify the primary domain name you want to configure for APACHE.",
		"  " + core.BOLD + "Examples:" + core.NC + " " + core.CYAN + "next-app.com" + core.NC + ", " + core.CYAN + "api.service.org" + core.NC + ", " + core.CYAN + "sub.domain.io" + core.NC,
	}
	tui.PrintInBox("--no-wait", "--help-str", "[Esc]  ->  Cancel & Return to Menu", "Add Virtual Host / Domain", cardLines)

	domainName, st := tui.ReadTextInput("Enter domain name", "")
	if st != 0 || strings.TrimSpace(domainName) == "" {
		logger.LogInfo("Cancelled by user.")
		return
	}
	domainName = system.CleanDomain(domainName)
	if !system.ValidateDomainName(domainName) {
		tui.PrintInBox("Validation Error", []string{
			core.RED + "Invalid domain name syntax. Must be a valid FQDN (e.g. example.com)." + core.NC,
			"",
			"Entered: " + domainName,
		})
		return
	}

	preset, ok := PromptVHostPreset()
	if !ok {
		logger.LogInfo("Cancelled by user.")
		return
	}

	targetOrPath := ""
	switch preset {
	case PresetNodeJS:
		tui.ClearScreen()
		pLines := []string{
			core.BOLD + core.CYAN + "Node.js Reverse Proxy Target" + core.NC,
			"",
			"  Enter the local backend URL and port where your Node.js/Next.js/NestJS app is listening.",
		}
		tui.PrintInBox("--no-wait", "Backend Upstream Target", pLines)
		pTarget, st := tui.ReadTextInput("Backend URL", "http://127.0.0.1:3000")
		if st != 0 || strings.TrimSpace(pTarget) == "" {
			return
		}
		if !system.ValidateProxyTarget(pTarget) {
			tui.PrintInBox("Invalid Proxy Target", []string{
				core.RED + "Proxy URL must be http:// or https:// without whitespace, embedded credentials, metadata IPs, or unsafe characters." + core.NC,
			})
			return
		}
		targetOrPath = strings.TrimSpace(pTarget)

	case PresetPython:
		tui.ClearScreen()
		pLines := []string{
			core.BOLD + core.CYAN + "Python Backend Target" + core.NC,
			"",
			"  Enter the local URL and port where Gunicorn/Uvicorn/FastAPI/Django is listening.",
		}
		tui.PrintInBox("--no-wait", "Backend Upstream Target", pLines)
		pTarget, st := tui.ReadTextInput("Backend URL", "http://127.0.0.1:8000")
		if st != 0 || strings.TrimSpace(pTarget) == "" {
			return
		}
		if !system.ValidateProxyTarget(pTarget) {
			tui.PrintInBox("Invalid Proxy Target", []string{
				core.RED + "Proxy URL must be http:// or https:// without whitespace, embedded credentials, metadata IPs, or unsafe characters." + core.NC,
			})
			return
		}
		targetOrPath = strings.TrimSpace(pTarget)

	case PresetSPA, PresetPHP, PresetStatic:
		tui.ClearScreen()
		pLines := []string{
			core.BOLD + core.CYAN + "Document Root Directory" + core.NC,
			"",
			"  Specify the directory on disk containing your HTML/dist/PHP files.",
		}
		tui.PrintInBox("--no-wait", "Document Root Setup", pLines)
		dPath, st := tui.ReadTextInput("Document Root", "/var/www/"+domainName)
		if st != 0 || strings.TrimSpace(dPath) == "" {
			return
		}
		dPath = strings.TrimSpace(dPath)
		if err := system.ValidateSafeDirectoryPath(dPath); err != nil {
			tui.PrintInBox("Invalid Document Root", []string{
				core.RED + err.Error() + core.NC,
			})
			return
		}
		targetOrPath = dPath
	}

	sslStrat, ok := system.PromptSSLStrategy(domainName)
	if !ok {
		logger.LogInfo("Cancelled by user.")
		return
	}

	// Universal firewall rules unblocking (UFW, Firewalld, iptables, ip6tables)
	system.ConfigureFirewallRules("80", "443")

	webUser := "apache"
	if core.SysInfo.Family == "debian" {
		webUser = "www-data"
		_ = exec.Command("a2enmod", "rewrite", "headers", "proxy", "proxy_http").Run()
		if sslStrat.Mode == "certbot" || sslStrat.Mode == "custom" {
			_ = exec.Command("a2enmod", "ssl").Run()
		}
		if sslStrat.Mode == "cloudflare" {
			_ = exec.Command("a2enmod", "remoteip").Run()
			system.ConfigureCloudflareRealIP()
		}
	}

	if preset == PresetSPA || preset == PresetPHP || preset == PresetStatic {
		if err := system.ValidateSafeDirectoryPath(targetOrPath); err != nil {
			logger.LogError("Aborting: " + err.Error())
			return
		}
		if system.IsSymlinkPath(targetOrPath) {
			logger.LogError("Aborting: document root must not be a symbolic link: " + targetOrPath)
			return
		}
		_ = os.MkdirAll(targetOrPath, 0755)
		system.SecureWebRootPermissions(targetOrPath, webUser)
	}

	srvDir := "/etc/apache2/sites-available"
	vhostFile := fmt.Sprintf("%s/%s.conf", srvDir, domainName)
	if core.SysInfo.Family != "debian" {
		srvDir = "/etc/httpd/conf.d"
		vhostFile = fmt.Sprintf("%s/%s.conf", srvDir, domainName)
	}

	_ = os.MkdirAll(srvDir, 0755)
	if core.SysInfo.Family != "debian" {
		_ = os.MkdirAll("/var/log/httpd", 0755)
	}

	vhostContent := GenerateTemplateVHost(domainName, preset, targetOrPath, sslStrat)
	if vhostContent == "" {
		logger.LogError("Aborting: generated Apache VirtualHost configuration is invalid.")
		return
	}
	if err := system.WriteFileNoFollow(vhostFile, []byte(vhostContent), 0644, ""); err != nil {
		logger.LogError("Failed to write virtual host config: " + err.Error())
		return
	}
	if core.SysInfo.Family == "debian" {
		_ = exec.Command("a2ensite", domainName+".conf").Run()
	}

	srvName := "apache2"
	if core.SysInfo.Family != "debian" {
		srvName = "httpd"
	}

	// If Certbot mode, run certbot to provision and wire the Let's Encrypt certificate
	sslFailed := false
	var sslErrLines []string
	if sslStrat.Mode == "certbot" {
		if system.IsLocalOrPrivateDomain(domainName) {
			logger.LogWarn(fmt.Sprintf("Skipping Let's Encrypt for local/private domain '%s'; configuring plain HTTP.", domainName))
			sslStrat.Mode = "none"
		} else {
			certbotReady := system.CommandExists("certbot")
			if !certbotReady {
				if core.SysInfo.Family == "debian" {
					certbotReady = system.RunStep("Installing Certbot", "apt-get", "install", "-y", "certbot", "python3-certbot-apache")
				} else if core.SysInfo.Family == "rhel" {
					if system.RunStep("Installing EPEL repository", "dnf", "install", "-y", "epel-release") {
						certbotReady = system.RunStep("Installing Certbot (EPEL)", "dnf", "install", "-y", "certbot", "python3-certbot-apache", "mod_ssl")
					}
				} else if core.SysInfo.Family == "alpine" {
					certbotReady = system.RunStep("Installing Certbot", "apk", "add", "--no-cache", "certbot", "certbot-apache")
				}
			}

			if !certbotReady {
				sslFailed = true
				sslErrLines = system.ExtractRecentLogErrors(core.LogFilePath, 4)
				sslStrat.Mode = "none"
			} else {
				tui.StartBoxSpinner(fmt.Sprintf("Requesting Let's Encrypt certificate for %s...", domainName))
				certArgs := []string{
					"--apache",
					"-d", domainName,
				}
				if addrs, err := net.LookupHost("www." + domainName); err == nil && len(addrs) > 0 {
					certArgs = append(certArgs, "-d", "www."+domainName)
				}
				certArgs = append(certArgs,
					"--non-interactive",
					"--agree-tos",
					"-m", sslStrat.Email,
					"--redirect",
				)
				if out, err := exec.Command("certbot", certArgs...).CombinedOutput(); err != nil {
					tui.StopBoxSpinner(1, "Certbot SSL acquisition failed.")
					sslFailed = true
					sslStrat.Mode = "none"
					logger.LogWarn(fmt.Sprintf("Let's Encrypt SSL acquisition failed for '%s': %s", domainName, strings.TrimSpace(string(out))))
					for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
						cleanL := strings.TrimSpace(core.SanitizeTerminalText(l))
						if cleanL != "" {
							sslErrLines = append(sslErrLines, cleanL)
							if len(sslErrLines) >= 4 {
								break
							}
						}
					}
					tui.ClearScreen()
					warnCard := []string{
						core.BOLD + core.YELLOW + "Let's Encrypt Validation Warning" + core.NC,
						"",
						fmt.Sprintf("  Certbot could not automatically verify '%s'.", domainName),
						"  Common causes:",
						"    1. Domain DNS A record does not point to this server IP yet.",
						"    2. External cloud firewall (Oracle Cloud/AWS Security List) drops port 80/443.",
						"    3. Domain is proxied by Cloudflare (use Cloudflare SSL mode instead).",
						"",
						core.BOLD + "Diagnostic Details:" + core.NC,
						core.DIM + core.SanitizeTerminalText(strings.TrimSpace(string(out))) + core.NC,
					}
					tui.PrintInBox("Certbot Notice", warnCard)
					time.Sleep(2500 * time.Millisecond)
				} else {
					tui.StopBoxSpinner(0, "SSL certificate generated successfully.")
				}
			}
		}
	}

	tui.ClearScreen()
	var testCmd *exec.Cmd
	if core.SysInfo.Family == "debian" {
		testCmd = exec.Command("apache2ctl", "-t")
	} else {
		testCmd = exec.Command("httpd", "-t")
	}

	out, testErr := testCmd.CombinedOutput()
	var addRes []string
	if testErr == nil {
		_ = exec.Command("systemctl", "reload", srvName).Run()
		statusVal := "SUCCESS"
		statusColor := core.GREEN
		sslDisplay := strings.ToUpper(sslStrat.Mode)
		sslColor := core.GREEN
		if sslStrat.Mode == "none" {
			sslColor = core.DIM
		}
		if sslFailed {
			statusVal = "PARTIAL (HTTP Active, SSL Failed)"
			statusColor = core.YELLOW
			sslDisplay = "NONE (Certbot Failed)"
			sslColor = core.RED
		}
		addRes = append(addRes, tui.FormatKV("Operation Status", statusVal, statusColor))
		addRes = append(addRes, tui.FormatKV("Target Domain", domainName, core.CYAN))
		addRes = append(addRes, tui.FormatKV("Preset Type", string(preset), core.CYAN))
		addRes = append(addRes, tui.FormatKV("Configuration File", vhostFile, core.YELLOW))
		addRes = append(addRes, tui.FormatKV("SSL/TLS Mode", sslDisplay, sslColor))
		addRes = append(addRes, tui.FormatKV("Apache Service", "Syntax OK & Service Reloaded", core.GREEN))
		if sslFailed {
			addRes = append(addRes, "")
			addRes = append(addRes, core.BOLD+core.YELLOW+"SSL CERTIFICATE NOTICE:"+core.NC)
			for _, el := range sslErrLines {
				addRes = append(addRes, "  "+core.RED+core.Sym.Pointer+" "+el+core.NC)
			}
			addRes = append(addRes, tui.FormatKV("Retry SSL", "sudo certbot --apache -d "+domainName, core.GREEN))
		}
		tui.PrintInBox("Add Virtual Host Result", addRes)
	} else {
		addRes = append(addRes, tui.FormatKV("Operation Status", "WARNING", core.YELLOW))
		addRes = append(addRes, tui.FormatKV("Target Domain", domainName, core.CYAN))
		addRes = append(addRes, tui.FormatKV("Configuration File", vhostFile, core.YELLOW))
		addRes = append(addRes, tui.FormatKV("Apache Service", "Syntax test failed!", core.RED))
		addRes = append(addRes, "")
		addRes = append(addRes, core.BOLD+"Syntax Diagnostics Output:"+core.NC)
		for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			addRes = append(addRes, "  "+core.RED+line+core.NC)
		}
		tui.PrintInBox("Add Virtual Host Result", addRes)
	}
}

